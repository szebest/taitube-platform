import { ErrorCodes } from '@vp/errors';
import { expectErr, expectOk } from '@vp/testing/result';
import type { Ref } from '../../schema/ref';
import { tokenFiles } from '../token-files';
import { fixtureScale, fixtureSets, fixtureTheme } from './fixture';

const offer = {
  typography: [fixtureSets.typography],
  fontSize: [fixtureSets.fontSize],
  spacing: [fixtureSets.spacing],
  sizing: [fixtureSets.sizing],
  radius: [fixtureSets.radius],
  border: [fixtureSets.border],
  shadow: [fixtureSets.shadow],
  ambient: [fixtureSets.ambient],
  motion: [fixtureSets.motion],
};

const dusk = {
  ...fixtureTheme,
  color: {
    ...fixtureTheme.color,
    dark: { ...fixtureTheme.color.dark, accent: '{ref.dusk.500}' as const },
  },
};

const filesFor = (ref: Ref) =>
  tokenFiles({ ref, scale: fixtureScale, themes: [dusk], defaultTheme: dusk, offer });

describe('tokenFiles', () => {
  it('writes the CSS with ramp steps resolved and tokens.json with the aliases kept', () => {
    const { tokensJson, themesCss, setsCss, tailwindThemeCss } = expectOk(
      filesFor({ dusk: { 500: '#C08040' } })
    );

    expect(themesCss).toContain('  --accent: #C08040;');
    expect(themesCss).not.toContain('{ref.');
    expect(JSON.parse(tokensJson).theme.dusk.dark.accent).toEqual({ $value: '{ref.dusk.500}' });
    expect(setsCss).toContain(':root {');
    expect(setsCss).toContain('[data-radius="square"] {');
    for (const file of [themesCss, setsCss, tailwindThemeCss]) {
      expect(file).toMatch(/^\/\* Generated by pnpm gen:tokens/);
    }
  });

  it('fails naming the role whose alias names no ramp step', () => {
    expect(expectErr(filesFor({}))).toEqual({
      code: ErrorCodes.VALIDATION_FAILED,
      message: expect.any(String),
      field: 'color.dark.accent',
    });
  });
});
