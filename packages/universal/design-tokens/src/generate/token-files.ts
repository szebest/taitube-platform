import { all, map, type Result } from '@vp/result';
import { type InvalidDefinition, resolveTheme } from '../parse';
import type { Ref } from '../schema/ref';
import type { Scale } from '../schema/scale';
import type { Theme } from '../schema/theme';
import { TOKEN_GROUPS } from '../schema/token-group';
import { type Offer, toDtcg } from './dtcg';
import { scaleCss } from './scale-css';
import { tailwindTheme } from './tailwind-theme';
import { themeCss } from './theme-css';
import { tokenSetCss } from './token-set-css';

export type TokenFiles = Readonly<{
  tokensJson: string;
  themesCss: string;
  setsCss: string;
  tailwindThemeCss: string;
}>;

const HEADER = '/* Generated by pnpm gen:tokens from the @vp/ui registry. Do not edit. */\n\n';

const css = (stylesheets: readonly string[]) => `${HEADER}${stylesheets.join('\n')}`;

export const tokenFiles = ({
  ref,
  scale,
  themes,
  defaultTheme,
  offer,
}: Readonly<{
  ref: Ref;
  scale: Scale;
  themes: readonly Theme[];
  defaultTheme: Theme;
  offer: Offer;
}>): Result<TokenFiles, InvalidDefinition> =>
  map(all(themes.map((theme) => resolveTheme(theme, ref))), (resolved) => ({
    tokensJson: `${JSON.stringify(toDtcg({ ref, scale, themes, offer }), null, 2)}\n`,
    themesCss: css(resolved.map(themeCss)),
    setsCss: css([
      scaleCss(scale),
      ...TOKEN_GROUPS.flatMap((group) => offer[group].map((set) => tokenSetCss(set))),
    ]),
    tailwindThemeCss: css([tailwindTheme(defaultTheme.defaults, scale)]),
  }));
