import type { EnvModel, EnvRow, ExtraRow } from './model';

const SCHEMA = 'packages/server/env-schema/src';

const INTRO = `# Environment reference

> Generated by \`pnpm gen:env-docs\`. Do not edit it by hand: change the sources and regenerate. CI fails
> when this file is stale. The sources are \`${SCHEMA}/app-env.ts\`, the \`env-docs-*.ts\` files beside it,
> \`platform-env.json\` and \`.env.example\`.

Every environment key the platform reads or hands to another tool, grouped as \`.env.example\` groups them.
Copy \`.env.example\` to \`.env\` for local development; a process validates its environment at boot and
exits with the list of invalid keys.

## Adding a key

1. Declare it in \`${SCHEMA}/app-env.ts\`: a secret uses \`secret()\` and has no default.
2. Document it in \`ENV_DOCS\`, in the group file under \`${SCHEMA}/env-docs-*.ts\`. A key outside the schema
   goes in \`${SCHEMA}/env-docs-extra.ts\`.
3. Add its line to \`.env.example\` under the matching \`# ----\` heading, a secret marked 🔒.

Then run \`pnpm gen:env-docs\` and commit this file with the change. Type and default come from the schema, so
they are never written twice.

How to read the tables: **Required in** says when the schema or a production boot refuses to start without
the key (\`always\`, \`production\`, \`AUTH_MODE=jwks\`). **Secret** keys have no default and show a placeholder
as their example. **Read by** names the runtime that reads the key.
`;

const slug = (title: string): string =>
  title
    .toLowerCase()
    .replace(/[^a-z0-9 -]/g, '')
    .replace(/ /g, '-');

const cell = (text: string): string => text.replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ');

const code = (text: string): string => `\`${cell(text)}\``;

const defaultCell = (text: string): string =>
  ['required', 'unset', 'empty'].includes(text) ? `*${text}*` : cell(text);

const yesNo = (flag: boolean): string => (flag ? 'yes' : 'no');

function table(header: string[], rows: string[][]): string {
  return [
    `| ${header.join(' | ')} |`,
    `| ${header.map(() => '---').join(' | ')} |`,
    ...rows.map((row) => `| ${row.join(' | ')} |`),
  ].join('\n');
}

function schemaTable(rows: EnvRow[]): string {
  return table(
    ['Name', 'Type', 'Default', 'Required in', 'Secret', 'Read by', 'Description', 'Example'],
    rows.map((row) => [
      code(row.name),
      cell(row.type),
      defaultCell(row.defaultText),
      cell(row.requiredIn) || '-',
      yesNo(row.secret),
      cell(row.readBy),
      cell(row.description),
      code(row.example),
    ])
  );
}

function extraTable(rows: ExtraRow[]): string {
  return table(
    ['Name', 'Secret', 'Read by', 'Description', 'Example'],
    rows.map((row) => [
      code(row.name),
      yesNo(row.secret),
      cell(row.consumer),
      cell(row.description),
      code(row.example),
    ])
  );
}

function section(title: string, summary: string, body: string): string {
  return `## ${title}\n\n${summary}\n\n${body}\n`;
}

function minimalLocal(model: EnvModel): string {
  const lines = model.minimalLocal.map(({ name, value }) => `${name}=${value}`).join('\n');
  return section(
    'Minimal local .env',
    'The keys with no default that the local stack needs, with the values `.env.example` ships for the compose services. Everything else falls back to the defaults below.',
    `\`\`\`dotenv\n${lines}\n\`\`\``
  );
}

/** `docs/ENVIRONMENT.md`, rendered from the model alone, so the same model always gives the same bytes. */
export function renderEnvDocs(model: EnvModel): string {
  const titles = [
    'Minimal local .env',
    ...model.groups.map(({ title }) => title),
    ...model.extras.map(({ title }) => title),
  ];
  const contents = titles.map((title) => `- [${title}](#${slug(title)})`).join('\n');

  const parts = [
    INTRO,
    `## Contents\n\n${contents}\n`,
    minimalLocal(model),
    ...model.groups.map(({ title, summary, rows }) => section(title, summary, schemaTable(rows))),
    ...model.extras.map(({ title, summary, rows }) => section(title, summary, extraTable(rows))),
  ];
  return parts.join('\n');
}
