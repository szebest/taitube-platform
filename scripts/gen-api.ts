import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, resolve } from 'node:path';
import ts from 'typescript';
import { surfaceOf } from './api-surface';
import { isPlatform, load, type Pkg } from './workspace-packages';

const USAGE = `Usage: pnpm gen:api [--check] [root]

Writes api/<name>.api.txt in every package under packages/platform/ except one that only ships
JSON presets: the names its exports map
makes public, each with its type, read through the TypeScript compiler API.

  --check   write nothing; exit 1 when a snapshot differs from what would be written
  --help    print this text

Exit codes: 0 up to date or written, 1 stale (--check), 2 bad arguments.
`;

const HEADER = 'Generated by pnpm gen:api from the exports map; edit the source, never this file.';

const isRecord = (value: unknown): value is Record<string, unknown> =>
  typeof value === 'object' && value !== null && !Array.isArray(value);

/** The source file an export entry points at: its `source` condition, else its `types` file mapped back from `dist`. */
function entryFile(target: unknown): string | undefined {
  if (typeof target === 'string') return target;
  if (!isRecord(target)) return undefined;
  if (typeof target.source === 'string') return target.source;
  return typeof target.types === 'string'
    ? target.types.replace(/^\.\/dist\//, './src/').replace(/\.d\.ts$/, '.ts')
    : undefined;
}

interface Entry {
  specifier: string;
  file: string | undefined;
}

function entriesOf(root: string, pkg: Pkg): Entry[] {
  const { exports } = JSON.parse(readFileSync(join(root, pkg.dir, 'package.json'), 'utf8'));
  const map = isRecord(exports) ? exports : { '.': 'src/index.ts' };
  return Object.entries(map)
    .sort(([a], [b]) => (a < b ? -1 : 1))
    .map(([subpath, target]) => {
      const file = entryFile(target);
      return {
        specifier: subpath === '.' ? pkg.name : `${pkg.name}/${subpath.slice(2)}`,
        file: file === undefined || subpath.includes('*') ? undefined : join(root, pkg.dir, file),
      };
    });
}

const isPresetsOnly = (entries: readonly Entry[]): boolean =>
  entries.length > 0 && entries.every(({ file }) => file?.endsWith('.json'));

function createProgram(root: string, files: string[]): ts.Program {
  const paths = Object.fromEntries(
    load(root).flatMap(({ name, dir }) => [
      [name, [join(root, dir, 'src/index.ts')]],
      [`${name}/*`, [join(root, dir, 'src/*')]],
    ])
  );
  return ts.createProgram(
    files,
    {
      target: ts.ScriptTarget.ES2022,
      lib: ['lib.es2022.d.ts', 'lib.dom.d.ts'],
      module: ts.ModuleKind.ESNext,
      moduleResolution: ts.ModuleResolutionKind.Bundler,
      jsx: ts.JsxEmit.ReactJSX,
      strict: true,
      noEmit: true,
      skipLibCheck: true,
      types: [],
      baseUrl: root,
      paths,
    },
    ts.createCompilerHost({})
  );
}

/** The snapshot file of each platform package, keyed by its path from the repository root. */
export function renderApis(root: string): Map<string, string> {
  const entries = new Map(
    load(root)
      .filter(({ dir }) => isPlatform(dir))
      .map((pkg) => [pkg, entriesOf(root, pkg)] as const)
      .filter(([, list]) => !isPresetsOnly(list))
  );
  const packages = [...entries.keys()];
  const files = [...entries.values()].flatMap((list) => list.flatMap(({ file }) => file ?? []));
  const program = createProgram(root, files);

  return new Map(
    packages.map((pkg) => {
      const blocks = (entries.get(pkg) ?? []).map(({ specifier, file }) => {
        const surface =
          file === undefined ? ['(pattern export, not enumerated)'] : surfaceOf(program, file);
        return [`## ${specifier}`, ...surface].join('\n');
      });
      const text = `# ${pkg.name}\n# ${HEADER}\n\n${blocks.join('\n\n')}\n`;
      return [join(pkg.dir, 'api', `${basename(pkg.dir)}.api.txt`), text];
    })
  );
}

interface Outcome {
  code: number;
  stdout: string;
  stderr: string;
}

export function run(argv: readonly string[], defaultRoot: string): Outcome {
  const flags = argv.filter((arg) => arg.startsWith('-'));
  const unknown = flags.find((flag) => !['--check', '--help', '-h'].includes(flag));
  if (unknown) {
    return { code: 2, stdout: '', stderr: `gen:api: unknown option ${unknown}\n${USAGE}` };
  }
  if (flags.includes('--help') || flags.includes('-h')) {
    return { code: 0, stdout: USAGE, stderr: '' };
  }

  const root = argv.find((arg) => !arg.startsWith('-')) ?? defaultRoot;
  const rendered = renderApis(root);

  if (!flags.includes('--check')) {
    for (const [file, text] of rendered) {
      mkdirSync(dirname(join(root, file)), { recursive: true });
      writeFileSync(join(root, file), text);
    }
    return { code: 0, stdout: `wrote ${rendered.size} api snapshots\n`, stderr: '' };
  }

  const stale = [...rendered].filter(
    ([file, text]) =>
      !existsSync(join(root, file)) || readFileSync(join(root, file), 'utf8') !== text
  );
  if (stale.length === 0) {
    return {
      code: 0,
      stdout: `gen:api: ${rendered.size} api snapshots are up to date\n`,
      stderr: '',
    };
  }
  return {
    code: 1,
    stdout: '',
    stderr: `gen:api: stale, run pnpm gen:api and commit it:\n${stale.map(([file]) => `  ${file}`).join('\n')}\n`,
  };
}

if (process.argv[1]?.endsWith('gen-api.ts')) {
  const outcome = run(process.argv.slice(2), resolve(import.meta.dirname, '..'));
  process.stdout.write(outcome.stdout);
  process.stderr.write(outcome.stderr);
  process.exitCode = outcome.code;
}
