import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { renderApis, run } from '../gen-api';

const SNAPSHOT = 'packages/platform/universal/ok/api/ok.api.txt';

const MANIFEST = {
  name: '@kit/ok',
  vp: { layer: 1 },
  exports: {
    '.': { types: './dist/index.d.ts', source: './src/index.ts' },
    './node': { types: './dist/node.d.ts', import: './dist/node.js' },
    './icons/*': './src/icons/*.ts',
  },
};

function write(root: string, files: Record<string, string>): void {
  for (const [path, text] of Object.entries(files)) {
    mkdirSync(dirname(join(root, path)), { recursive: true });
    writeFileSync(join(root, path), text);
  }
}

function tree(): string {
  const root = mkdtempSync(join(tmpdir(), 'gen-api-'));
  onTestFinished(() => rmSync(root, { recursive: true, force: true }));
  write(root, {
    'packages/platform/universal/ok/package.json': JSON.stringify(MANIFEST),
    'packages/platform/universal/ok/src/index.ts':
      "import { double } from '@kit/other';\nexport const twice = (n: number): number => double(n);\n",
    'packages/platform/universal/ok/src/node.ts': 'export const runtime = (): string => "node";\n',
    'packages/platform/universal/other/package.json': JSON.stringify({
      name: '@kit/other',
      vp: { layer: 0 },
      exports: { '.': { source: './src/index.ts' } },
    }),
    'packages/platform/universal/other/src/index.ts':
      'export const double = (n: number): number => n * 2;\n',
    'packages/platform/universal/presets/package.json': JSON.stringify({
      name: '@kit/presets',
      vp: { layer: 1 },
      exports: { './base.json': './base.json', './client.json': './client.json' },
    }),
    'packages/platform/universal/presets/base.json': '{}',
    'packages/platform/universal/presets/client.json': '{}',
    'packages/universal/app/package.json': JSON.stringify({ name: '@vp/app', vp: { layer: 1 } }),
    'packages/universal/app/src/index.ts': 'export const app = 1;\n',
  });
  return root;
}

describe('scripts: pnpm gen:api', () => {
  it('describes each platform package by its exports map, the source of every entry, and neither an app package nor a presets-only one', () => {
    const rendered = renderApis(tree());

    expect([...rendered.keys()]).toEqual([
      SNAPSHOT,
      'packages/platform/universal/other/api/other.api.txt',
    ]);
    expect(rendered.get(SNAPSHOT)).toBe(
      [
        '# @kit/ok',
        '# Generated by pnpm gen:api from the exports map; edit the source, never this file.',
        '',
        '## @kit/ok',
        'export const twice: (n: number) => number',
        '',
        '## @kit/ok/icons/*',
        '(pattern export, not enumerated)',
        '',
        '## @kit/ok/node',
        'export const runtime: () => string',
        '',
      ].join('\n')
    );
  });

  it('writes the files the check reads, and the check names the snapshot a source change left behind', () => {
    const root = tree();

    expect(run([root], '/nowhere')).toEqual({
      code: 0,
      stdout: 'wrote 2 api snapshots\n',
      stderr: '',
    });
    expect(run(['--check', root], '/nowhere')).toMatchObject({ code: 0 });

    write(root, { 'packages/platform/universal/ok/src/node.ts': 'export const runtime = 1;\n' });

    expect(run(['--check', root], '/nowhere')).toEqual({
      code: 1,
      stdout: '',
      stderr: `gen:api: stale, run pnpm gen:api and commit it:\n  ${SNAPSHOT}\n`,
    });
  });

  it('records a package the same whatever other platform packages the tree holds', () => {
    const root = tree();
    write(root, {
      'packages/platform/universal/ok/src/node.ts':
        "export const runtime = (flag: boolean) => (flag ? 'node' : 'bun');\n",
    });
    const alone = renderApis(root).get(SNAPSHOT);

    write(root, {
      'packages/platform/universal/aaa/package.json': JSON.stringify({
        name: '@kit/aaa',
        vp: { layer: 0 },
        exports: { '.': { source: './src/index.ts' } },
      }),
      'packages/platform/universal/aaa/src/index.ts':
        "export const order = (flag: boolean) => (flag ? 'bun' : 'node');\n",
    });

    expect(renderApis(root).get(SNAPSHOT)).toBe(alone);
  });

  it('calls a package with no snapshot stale', () => {
    const outcome = run(['--check', tree()], '/nowhere');

    expect(outcome.code).toBe(1);
    expect(outcome.stderr).toContain(SNAPSHOT);
  });

  it.each([
    { argv: ['--help'], code: 0 },
    { argv: ['--wat'], code: 2 },
  ])('exits $code for $argv', ({ argv, code }) => {
    expect(run(argv, '/nowhere').code).toBe(code);
  });

  it('leaves what it wrote readable as text', () => {
    const root = tree();
    run([root], '/nowhere');

    expect(readFileSync(join(root, SNAPSHOT), 'utf8').endsWith('\n')).toBe(true);
  });
});
