(() => {
  const el = (tag, props = {}, children = []) => {
    const node = Object.assign(document.createElement(tag), props);
    node.append(...children);
    return node;
  };

  const board = (screen) => {
    const frame = el('div', { className: screen.phone ? 'frame frame--phone' : 'frame' }, [
      el('iframe', { src: screen.path, title: screen.title, loading: 'lazy', tabIndex: -1 }),
      el('a', { href: screen.path, ariaLabel: `Open ${screen.title}` }),
    ]);
    return el('article', { className: 'board' }, [frame, el('span', { className: 'tt-label', textContent: screen.title }), el('span', { className: 'tt-caption tt-muted', textContent: screen.path })]);
  };
  const link = (doc) => el('a', { href: doc.path }, [el('span', { className: 'tt-label', textContent: doc.title }), el('small', { textContent: doc.summary })]);
  const asset = (item) => el('figure', { className: 'asset' }, [el('div', {}, [el('img', { src: item.path, alt: '' })]), el('figcaption', { className: 'tt-caption tt-muted', textContent: item.title })]);

  document.getElementById('web').replaceChildren(...LIBRARY.screens.web.map(board));
  document.getElementById('studio').replaceChildren(...LIBRARY.screens.studio.map(board));
  document.getElementById('states').replaceChildren(...LIBRARY.screens.states.map(board));
  document.getElementById('foundations').replaceChildren(...LIBRARY.foundations.map(link));
  document.getElementById('components').replaceChildren(...LIBRARY.primitives.map(link));
  document.getElementById('patterns').replaceChildren(...[...LIBRARY.components, ...LIBRARY.web, ...LIBRARY.studio].map(link));
  document.getElementById('assets').replaceChildren(...LIBRARY.assets.map(asset));

  // Every board is its own page with its own design.js; reload them when the appearance changes here.
  document.addEventListener('tt:appearance', () => {
    for (const frame of document.querySelectorAll('.frame iframe')) {
      try {
        frame.contentWindow?.location.reload();
      } catch {
        // A board that has not loaded yet picks up the saved appearance when it does.
      }
    }
  });
})();
